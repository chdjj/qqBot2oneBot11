import { JSDOM } from 'jsdom';
import fs from 'node:fs';
import vm from 'node:vm';
const BASE = process.env.BASE || 'http://127.0.0.1:18080';
const html = fs.readFileSync('E:/qqbottoonebot/internal/api/web/index.html', 'utf8');
const dom = new JSDOM(html.replace('/static/app.js', ''), { url: BASE + '/', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.fetch = (i, o) => fetch(String(i).startsWith('http') ? i : BASE + i, o);
w.WebSocket = class { constructor() { setTimeout(() => this.onopen && this.onopen(), 5); } close() {} };
w.confirm = () => true;
vm.runInContext(fs.readFileSync('E:/qqbottoonebot/internal/api/web/app.js', 'utf8'), dom.getInternalVMContext(), { filename: 'app.js' });
await new Promise(r => setTimeout(r, 1400));
const $ = (s) => w.document.querySelector(s);
const $$ = (s) => Array.from(w.document.querySelectorAll(s));
console.log('pulse:', $('#pulse-text').textContent.trim());
console.log('metrics:', $$('#metrics .metric').length);
console.log('overview empty:', $('#overview-bots').textContent.trim());
$$('.nav button').find(b => b.dataset.view === 'bots').click();
await new Promise(r => setTimeout(r, 120));
console.log('bot-empty visible:', !$('#bot-empty').hidden, '|', $('#bot-empty').textContent.trim().replace(/\s+/g, ' ').slice(0, 40));
$('#btn-add-bot').click();
await new Promise(r => setTimeout(r, 120));
console.log('modal open:', !$('#modal').hidden, '| title:', $('#modal-title').textContent);
console.log('fields:', $$('#modal-body input').map(i => i.name).join(','));
$$('.nav button').find(b => b.dataset.view === 'listeners').click();
$('#btn-add-listener').click();
await new Promise(r => setTimeout(r, 120));
const toasts = w.document.querySelectorAll('.toast');
console.log('add-listener-without-bot -> toasts:', toasts.length, toasts[0] ? toasts[0].textContent : '');
process.exit(0);
